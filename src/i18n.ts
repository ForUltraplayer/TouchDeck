const DICTIONARIES: Record<Language, Record<TKey, string>> = { ko, en, ja };

export const LANGUAGES: Language[] = ["ko", "en", "ja"];

// Narrows a language code from outside the frontend; anything unsupported becomes English
export const toLanguage = (value: string): Language =>
  LANGUAGES.find((l) => l === value) ?? "en";

export type Translate = (key: TKey, params?: Record<string, string | number>) => string;

export function translate(
  language: Language,
  key: TKey,
  params?: Record<string, string | number>
): string {
  const template = (DICTIONARIES[language] ?? en)[key];
  // Single pass over the template, so braces inside a substituted value are left alone
  return params
    ? template.replace(/\{(\w+)\}/g, (match, name: string) =>
        name in params ? String(params[name]) : match
      )
    : template;
}

export const createI18n = (language: Language): { language: Language; t: Translate } => ({
  language,
  t: (key, params) => translate(language, key, params),
});

const I18nContext = createContext(createI18n("en"));

export const I18nProvider = I18nContext.Provider;

export const useI18n = () => useContext(I18nContext);
